import { promises as fsp } from "node:fs";
import path from "node:path";
import type { PostStore } from "./deps.js";
import type { TitleInput, TitleStep } from "./types.js";

/** Marks an .nfo as Harvest's: only these are ever overwritten, or deleted when the mirror removes the video. */
export const NFO_MARKER = "<!-- generated by Harvest -->";
export const VIDEO_EXTENSIONS = new Set([".mkv", ".mp4", ".m4v", ".avi", ".mov", ".wmv", ".ts"]);
export const MAX_STRIP_LENGTH = 200;

const xmlEscape = (s: string): string => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Comma-separated tokens, trimmed, lowercased, empties dropped. */
export const parseStrip = (raw: string): string[] => raw.split(",").map((t) => t.trim().toLowerCase()).filter(Boolean);

/** The video's filename without extension, dots and underscores to spaces, listed release tokens removed. Empty when nothing is left. */
export function titleFromFilename(file: string, strip: readonly string[]): string {
  const base = path.basename(file, path.extname(file));
  const drop = new Set(strip.map((t) => t.toLowerCase()));
  return base.split(/[._]+/).filter((tok) => tok !== "" && !drop.has(tok.toLowerCase())).join(" ").replace(/\s+/g, " ").trim();
}

export function nfoXml(title: string): string {
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n${NFO_MARKER}\n<episodedetails>\n  <title>${xmlEscape(title)}</title>\n</episodedetails>\n`;
}

export const nfoPathFor = (video: string): string => video.slice(0, video.length - path.extname(video).length) + ".nfo";

/** True when the file at `p` exists and carries Harvest's marker. */
export async function isHarvestNfo(p: string): Promise<boolean> {
  try {
    const st = await fsp.lstat(p);
    if (!st.isFile() || st.size > 64 * 1024) return false;
    return (await fsp.readFile(p, "utf8")).includes(NFO_MARKER);
  } catch {
    return false;
  }
}

/** Deletes the Harvest-generated .nfo next to `video`, if any. Never throws. */
export async function removeTitleNfo(video: string): Promise<void> {
  const nfo = nfoPathFor(video);
  if (await isHarvestNfo(nfo)) await fsp.rm(nfo, { force: true }).catch(() => undefined);
}

type Deps = { postStore: PostStore };

/**
 * Runs in staging before promote. For each staged video writes `<name>.nfo` beside it. An .nfo that is already there and is not
 * Harvest's (the remote shipped one) is left alone. Re-running after a crash overwrites our own file.
 */
export function createTitleStep(deps: Deps): TitleStep {
  return {
    async run(input: TitleInput) {
      const cfg = deps.postStore.get(input.job.id);
      const warnings: string[] = [];
      const added: string[] = [];
      if (!cfg.titleNfo) return { warnings, added };
      const strip = parseStrip(cfg.titleStrip);
      for (const video of input.files) {
        if (!VIDEO_EXTENSIONS.has(path.extname(video).toLowerCase())) continue;
        const nfo = nfoPathFor(video);
        const title = titleFromFilename(video, strip);
        if (title === "") { warnings.push(`title nfo skipped for ${path.basename(video)}: nothing left of the name after removing the listed tokens`); continue; }
        const exists = await fsp.lstat(nfo).then(() => true, () => false);
        if (exists && !(await isHarvestNfo(nfo))) continue;
        await fsp.writeFile(nfo, nfoXml(title), "utf8");
        added.push(nfo);
      }
      return { warnings, added };
    },
  };
}
